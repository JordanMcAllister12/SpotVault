/**
 * Build-time image manifest generator.
 *
 * Scans public/ and src/ for all image references and writes a JSON manifest
 * that the Image Vault can use to inventory images without filesystem access
 * in the browser.
 *
 * Output: src/data/imageManifest.ts (typed TypeScript module)
 */
import { readdirSync, statSync, readFileSync, existsSync } from 'fs';
import { join, relative, extname } from 'path';

const PROJECT_ROOT = join(__dirname, '..');
const PUBLIC_DIR = join(PROJECT_ROOT, 'public');
const SRC_DIR = join(PROJECT_ROOT, 'src');
const OUTPUT_FILE = join(SRC_DIR, 'data', 'imageManifest.ts');

interface ManifestEntry {
  path: string;
  filename: string;
  directory: string;
  extension: string;
  category: 'public' | 'bundled';
  sizeBytes: number;
}

const IMAGE_EXTENSIONS = new Set(['.png', '.jpg', '.jpeg', '.webp', '.svg', '.gif', '.avif']);

function scanDirectory(dir: string, category: 'public' | 'bundled', baseDir: string): ManifestEntry[] {
  const entries: ManifestEntry[] = [];
  if (!existsSync(dir)) return entries;

  for (const item of readdirSync(dir)) {
    const fullPath = join(dir, item);
    const stat = statSync(fullPath);
    if (stat.isDirectory()) {
      entries.push(...scanDirectory(fullPath, category, baseDir));
    } else if (IMAGE_EXTENSIONS.has(extname(item).toLowerCase())) {
      const relPath = relative(baseDir, fullPath).replace(/\\/g, '/');
      const isPublic = category === 'public';
      entries.push({
        path: isPublic ? `/${relPath}` : relPath,
        filename: item,
        directory: relative(baseDir, dir).replace(/\\/g, '/') || '/',
        extension: extname(item).toLowerCase().slice(1),
        category,
        sizeBytes: stat.size,
      });
    }
  }
  return entries;
}

function scanCodeReferences(srcDir: string): Record<string, string[]> {
  const references: Record<string, string[]> = {};
  if (!existsSync(srcDir)) return references;

  function scanDir(dir: string) {
    for (const item of readdirSync(dir)) {
      const fullPath = join(dir, item);
      const stat = statSync(fullPath);
      if (stat.isDirectory()) {
        scanDir(fullPath);
      } else if (/\.(tsx?|jsx?|css)$/.test(item)) {
        const content = readFileSync(fullPath, 'utf-8');
        const relFile = relative(SRC_DIR, fullPath).replace(/\\/g, '/');

        // Match patterns like /assets/... or /image... in src attributes and url()
        const matches = content.matchAll(/['"`](\/(?:assets|image|public)[^'"`)]*\.(?:png|jpe?g|webp|svg|gif|avif)['"`]/gi);
        for (const m of matches) {
          const imgPath = m[0].replace(/['"`]/g, '');
          if (!references[imgPath]) references[imgPath] = [];
          if (!references[imgPath].includes(relFile)) {
            references[imgPath].push(relFile);
          }
        }

        // Match relative imports of images
        const importMatches = content.matchAll(/import\s+[^'"]*['"]([^'"]+\.(?:png|jpe?g|webp|svg|gif|avif))['"]/gi);
        for (const m of importMatches) {
          const imgPath = m[1];
          if (!references[imgPath]) references[imgPath] = [];
          if (!references[imgPath].includes(relFile)) {
            references[imgPath].push(relFile);
          }
        }
      }
    }
  }
  scanDir(srcDir);
  return references;
}

console.log('Scanning public/ for images...');
const publicImages = scanDirectory(PUBLIC_DIR, 'public', PROJECT_ROOT);
console.log(`Found ${publicImages.length} images in public/`);

console.log('Scanning src/ for code references...');
const codeReferences = scanCodeReferences(SRC_DIR);
console.log(`Found ${Object.keys(codeReferences).length} referenced image paths`);

const manifest = {
  generatedAt: new Date().toISOString(),
  publicImages,
  codeReferences,
};

const output = `// AUTO-GENERATED by scripts/generate-image-manifest.ts — do not edit manually.
// Regenerate with: npx tsx scripts/generate-image-manifest.ts

export interface ManifestImageEntry {
  path: string;
  filename: string;
  directory: string;
  extension: string;
  category: 'public' | 'bundled';
  sizeBytes: number;
}

export interface ImageManifest {
  generatedAt: string;
  publicImages: ManifestImageEntry[];
  codeReferences: Record<string, string[]>;
}

export const imageManifest: ImageManifest = ${JSON.stringify(manifest, null, 2)};

export const manifestImageCount = ${publicImages.length};
export const manifestReferencedCount = ${Object.keys(codeReferences).length};
`;

import { writeFileSync, mkdirSync } from 'fs';
mkdirSync(join(SRC_DIR, 'data'), { recursive: true });
writeFileSync(OUTPUT_FILE, output);
console.log(`Manifest written to ${relative(PROJECT_ROOT, OUTPUT_FILE)} (${publicImages.length} images, ${Object.keys(codeReferences).length} referenced paths)`);
